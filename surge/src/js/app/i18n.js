      'ann.gameOverHigh': 'Fin de la carrera. ¡Nuevo récord, {score} puntos!',
      'ann.status': 'Puntos {score}, {distance} metros, {speed} metros por segundo. Vida {hp}. {coins} monedas, {gems} gemas, {cores} núcleos. {kills} derribos.',
      'ann.envInfo': 'Mundo {env}. Arma {weapon}. {envDesc}',
